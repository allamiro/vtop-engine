#!/usr/bin/env python3
"""Regenerate every Kafka-comparison chart and report from the committed runs (#600).

    python3 -m pip install -r benchmarks/kafka_compare/requirements-report.txt
    python3 benchmarks/kafka_compare/regenerate.py
    git diff --exit-code -- docs/benchmarks/        # what CI does next

Every run directory COMMITTED under benchmarks/kafka_compare/results/ is
handed to report.py, the one entry point that knows which generator a run
needs (a failover run goes on to failover_report.py by its failover.csv). A new
kind of run is covered the day its results are committed, with no change here
or in CI. An uncommitted local run, staged or not, is ignored: the drift check
is about what HEAD says, so every comparison here (runs, stale output, the
committed PNG bytes) reads HEAD, never the index or the working tree.

Refuses, exit 2, writing nothing first:
- a plotting stack other than requirements-report.txt pins, or a DejaVu Sans
  resolved from outside matplotlib's own data (a system copy of the font is
  not the one the committed images were drawn with);
- no committed run at all (a drift check over nothing proves nothing);
- a committed run whose files on disk differ from HEAD (staged, unstaged or
  untracked): report.py reads the run from disk, and the check vouches for
  what HEAD says.
Refuses, exit 2, after regenerating:
- two runs writing the same file: the last would silently win, and the drift
  check would vouch only for it;
- a committed image under docs/benchmarks/img/, or a committed page marked as
  generated, that no run writes: a chart left behind by a rename is stale
  output nobody can regenerate.
A run report.py refuses fails this with report.py's own exit code and reason.

PNG bytes vs pixels. The SVG and Markdown output is byte-identical on every
host tried (macOS arm64, Linux arm64, Linux x86_64) with the pinned stack. The
PNG PIXELS are too, but the PNG BYTES are not: Pillow's macOS and manylinux
wheels deflate with different zlib builds, so the same pixels compress to
different bytes (the 1500x750 produce-throughput chart: 104,208 bytes on
macOS, 120,586 on both Linux architectures, zero differing pixels). So a PNG
whose decoded pixels, size, mode and metadata equal the committed file's is
put back to the committed bytes, and only a real visual change reaches
`git diff`. Any change in an SVG or the Markdown is a byte difference as usual.
"""
from __future__ import annotations

import argparse
import io
import os
import shlex
import subprocess
import sys
from collections.abc import Callable, Iterable

HERE = os.path.dirname(os.path.realpath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
REPORT = os.path.join(HERE, "report.py")
PINS = os.path.join(HERE, "requirements-report.txt")
RESULTS = "benchmarks/kafka_compare/results"
OUTPUT = "docs/benchmarks"
IMAGES = "docs/benchmarks/img"
GENERATED_MARK = "<!-- Generated by benchmarks/kafka_compare/"


class Refused(Exception):
    """The regeneration cannot vouch for the committed output; the message says why."""


def _git(repo: str, *args: str, binary: bool = False):
    out = subprocess.run(["git", *args], cwd=repo, check=True, capture_output=True)
    return out.stdout if binary else out.stdout.decode()


def _committed_names(repo: str, prefix: str) -> list[str]:
    """Paths under `prefix` in HEAD. Not `git ls-files`: that reads the index, where a staged but
    uncommitted run would count as committed."""
    out = _git(repo, "ls-tree", "-r", "-z", "--name-only", "HEAD", "--", prefix)
    return [name for name in out.split("\0") if name]


# ------------------------------------------------------------------ environment


def read_pins(path: str = PINS) -> dict[str, str]:
    pins = {}
    with open(path) as handle:
        for line in handle:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            name, sep, version = line.partition("==")
            if not sep or not version.strip():
                raise Refused(f"{path}: `{line}` is not an exact `name==version` pin")
            pins[name.strip().lower()] = version.strip()
    if not pins:
        raise Refused(f"{path}: no pins")
    return pins


def check_stack(pins: dict[str, str], installed: Callable[[str], str | None] | None = None) -> None:
    """Refuse unless every pinned package is installed at exactly its pinned version."""
    if installed is None:
        from importlib import metadata

        def installed(name: str) -> str | None:
            try:
                return metadata.version(name)
            except metadata.PackageNotFoundError:
                return None

    wrong = []
    for name, want in sorted(pins.items()):
        have = installed(name)
        if have != want:
            wrong.append(f"{name} {have or 'not installed'} (pinned {want})")
    if wrong:
        raise Refused("the plotting stack is not the pinned one: " + "; ".join(wrong) +
                      f". Install it with `python3 -m pip install -r {os.path.relpath(PINS, REPO)}`.")


def check_font() -> None:
    """Refuse unless matplotlib resolves report.py's font to its own bundled copy."""
    import matplotlib
    from matplotlib import font_manager

    path = font_manager.findfont(font_manager.FontProperties(family="DejaVu Sans"), fallback_to_default=False)
    data = os.path.realpath(matplotlib.get_data_path())
    if not os.path.realpath(path).startswith(data + os.sep):
        raise Refused(f"DejaVu Sans resolves to {path}, not to matplotlib's bundled copy under {data}")


# ------------------------------------------------------------------------- runs


def committed_runs(repo: str = REPO) -> list[str]:
    """Every run directory (results/<run-id>) with at least one committed file, sorted."""
    names = _committed_names(repo, RESULTS)
    runs = set()
    for name in filter(None, names):
        parts = name[len(RESULTS) + 1:].split("/")
        if len(parts) > 1:
            runs.add(os.path.join(repo, RESULTS, parts[0]))
    if not runs:
        raise Refused(f"no committed run under {RESULTS}/: nothing to regenerate, so nothing is checked")
    return sorted(runs)


def check_runs_unchanged(runs: Iterable[str], repo: str = REPO) -> None:
    """Refuse when a committed run's files on disk are not HEAD's: report.py reads the run from disk,
    so a staged, unstaged or untracked change inside it would be regenerated as if HEAD said it.
    Raw data is not edited in place; a re-run is a new run directory."""
    problems = []
    for run in runs:
        rel = os.path.relpath(run, repo)
        quoted = shlex.quote(rel)
        # Against HEAD, not the index: a staged edit is as uncommitted as an unstaged one.
        diff = sorted(filter(None, _git(repo, "diff", "--name-only", "HEAD", "--", rel).split("\n")))
        untracked = sorted(filter(None, _git(repo, "ls-files", "--others", "--exclude-standard", "--",
                                             rel).split("\n")))
        # Each hint names the run directory, so it can be pasted as printed.
        if diff:
            problems.append(f"{rel}: changed from HEAD: {', '.join(diff)}; commit them, or restore the run "
                            f"with `git restore --staged --worktree -- {quoted}`")
        if untracked:
            problems.append(f"{rel}: untracked: {', '.join(untracked)}; commit them, or delete them "
                            f"(`git clean -n -- {quoted}` to preview, `git clean -f -- {quoted}` to delete)")
    if problems:
        raise Refused("a committed run differs from HEAD on disk: " + " | ".join(problems))


def run_report(run_dir: str) -> list[str]:
    """report.py on one run, in its own interpreter as a developer runs it; the paths it wrote."""
    proc = subprocess.run([sys.executable, REPORT, run_dir], capture_output=True, text=True)
    if proc.returncode != 0:
        raise ReportFailed(run_dir, proc.returncode, proc.stderr.strip())
    return [os.path.realpath(line) for line in proc.stdout.splitlines() if line.strip()]


class ReportFailed(Exception):
    def __init__(self, run_dir: str, code: int, stderr: str):
        super().__init__(f"report.py {run_dir} exited {code}: {stderr or '(no stderr)'}")
        self.code = code


def regenerate(runs: Iterable[str], report: Callable[[str], list[str]] = run_report) -> dict[str, str]:
    """Run every run through report.py; {written path: the run that wrote it}. Refuses a path written twice."""
    owner: dict[str, str] = {}
    clashes = []
    for run in runs:
        for path in report(run):
            if path in owner:
                clashes.append(f"{path} (by {owner[path]} and {run})")
            owner[path] = run
    if clashes:
        raise Refused("two runs write the same file, so only the last is checked: " + "; ".join(clashes))
    return owner


def orphans(written: Iterable[str], repo: str = REPO) -> list[str]:
    """Committed generated output that no run wrote: every file under IMAGES, and every page under
    OUTPUT carrying the generated mark."""
    written = {os.path.realpath(path) for path in written}
    stale = []
    for name in _committed_names(repo, OUTPUT):
        path = os.path.realpath(os.path.join(repo, name))
        if path in written:
            continue
        if name.startswith(IMAGES + "/"):
            stale.append(name)
        elif name.endswith(".md") and os.path.isfile(path):
            with open(path, encoding="utf-8") as handle:
                if GENERATED_MARK in handle.read():
                    stale.append(name)
    return sorted(stale)


# -------------------------------------------------------------------------- png


def same_png(a: bytes, b: bytes) -> bool:
    """Whether two PNGs decode to the same image: size, mode, metadata and every pixel."""
    from PIL import Image

    with Image.open(io.BytesIO(a)) as one, Image.open(io.BytesIO(b)) as two:
        return (one.size == two.size and one.mode == two.mode and one.info == two.info
                and one.tobytes() == two.tobytes())


def keep_committed_pngs(written: Iterable[str], repo: str = REPO) -> list[str]:
    """Put back the committed bytes of every written PNG whose image did not change. Returns those paths."""
    kept = []
    for path in sorted(written):
        if not path.endswith(".png"):
            continue
        name = os.path.relpath(path, os.path.realpath(repo))
        try:
            committed = _git(repo, "show", f"HEAD:{name}", binary=True)
        except subprocess.CalledProcessError:
            continue  # output HEAD does not have: `git status` reports it
        with open(path, "rb") as handle:
            fresh = handle.read()
        if fresh != committed and same_png(fresh, committed):
            with open(path, "wb") as handle:
                handle.write(committed)
            kept.append(path)
    return kept


# ------------------------------------------------------------------------- main


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.parse_args(argv)
    try:
        check_stack(read_pins())
        check_font()
        runs = committed_runs()
        check_runs_unchanged(runs)
        owner = regenerate(runs)
        stale = orphans(owner)
        if stale:
            raise Refused("committed output that no run writes (stale; delete it or restore its generator): "
                          + ", ".join(stale))
        kept = keep_committed_pngs(owner)
    except Refused as exc:
        print(f"regenerate refused: {exc}", file=sys.stderr)
        return 2
    except ReportFailed as exc:
        print(f"regenerate failed: {exc}", file=sys.stderr)
        return exc.code
    for run in runs:
        print(f"run {os.path.relpath(run, REPO)}")
    for path in sorted(owner):
        note = " (pixels unchanged: committed bytes kept)" if path in kept else ""
        print(f"  wrote {os.path.relpath(path, REPO)}{note}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Charts, tables and the scoreboard of a cross-product run, from its committed CSV (#744 section 5).

Every number comes from the run's CSV and every condition from its
`environment.json` (#595 rule 9); `schema.load_run` refuses a partial, mixed
or unchartable run before anything is written. Each kind supplies a `Report`
spec (its metrics, charts and fixed text) and this module draws it:

- grouped bars: the bar is the median of the repetitions (or the sum, for
  counts such as gaps after kills), the whisker min to max, bars from zero, no
  log axis; a cell where a system has no usable value is a hatched stub
  labelled `failed`, `refused` or `not sustained`, never a missing bar; a zero
  is drawn and labelled;
- colours from the family order (`colours.series`), one per system, never by
  rank; each system is drawn in its PRIMARY profile (the first the plan lists
  for it). Other profiles, VTOP's labelled `verify-off` among them, are in the
  tables, never as a second bar of the same colour;
- a table of the same numbers under every chart;
- the scoreboard (#744 section 5.3): for every metric and group, the best
  system, its value, VTOP's value and VTOP's ratio to the best, with VTOP's row
  present even when VTOP is last; and the sentences that say where VTOP is
  ahead, level and behind, generated from those rows only.

Output is deterministic for a given CSV, environment and plotting stack (the
Kafka comparison's pinned stack, fixed rcParams and SVG hash salt, no
timestamps in metadata).
"""
from __future__ import annotations

import os
from collections.abc import Callable, Sequence
from typing import Any, NamedTuple

from compare_common import colours, registry, schema
from kafka_compare import stats

GENERATED_MARK = "<!-- Generated by benchmarks/compare_common/report.py"
SURFACE = "#fcfcfb"
INK = "#0b0b0b"
INK_2 = "#52514e"
GRID = "#e2e1dc"
LEVEL_BAND = 0.05  # within 5% of the best is "level"


class Metric(NamedTuple):
    id: str
    label: str  # axis and table label, with its unit
    column: str
    better: str  # "higher" or "lower"
    cells: tuple[str, ...]
    reduce: str = "median"  # or "sum" (counts across repetitions, e.g. gaps after kills)
    digits: int = 1


class Chart(NamedTuple):
    name: str  # file stem
    title: str
    subtitle: str
    metrics: tuple[Metric, ...]  # one panel each


class Report(NamedTuple):
    kind: schema.Kind
    title: str
    doc_name: str  # docs/benchmarks/<doc_name>.md
    img_dir: str  # docs/benchmarks/<img_dir>/
    intro: str
    charts: tuple[Chart, ...]
    group_label: Callable[[str, dict[str, str]], str]
    notes: str = ""


class Value(NamedTuple):
    """One bar: a summary of the ok repetitions, or the stub reason when there are none."""

    summary: stats.Summary | None
    stub: str | None
    reps: int


def primary_profile(plan: dict[str, Any], system: str) -> str:
    profiles = (plan.get("profiles") or {}).get(system) or []
    if not profiles:
        for cell in plan.get("cells", []):
            profiles = (cell.get("profiles") or {}).get(system) or []
            if profiles:
                break
    if not profiles:
        raise schema.RunRefused(f"the plan names no profile for {system}")
    return profiles[0]


def groups(rows: Sequence[dict[str, str]], kind: schema.Kind, metric: Metric) -> list[tuple[str, tuple[str, ...]]]:
    """(cell, variant values) in first-seen order among the metric's cells."""
    out: list[tuple[str, tuple[str, ...]]] = []
    for cell in metric.cells:
        for row in rows:
            if row["cell"] != cell:
                continue
            group = (cell, tuple(row[column] for column in kind.variant_columns))
            if group not in out:
                out.append(group)
    return out


def value(rows: Sequence[dict[str, str]], kind: schema.Kind, metric: Metric, group: tuple[str, tuple[str, ...]],
          system: str, profile: str) -> Value:
    cell, variant = group
    selected = [row for row in rows if row["cell"] == cell and row["system"] == system and row["profile"] == profile
                and tuple(row[column] for column in kind.variant_columns) == variant]
    usable, stubs = [], []
    for row in selected:
        if row["status"] != "ok":
            stubs.append(row["status"])
        elif row.get("sustained", "") == "false":
            stubs.append("not sustained")
        elif row.get(metric.column, "") == "":
            stubs.append("not measured")
        else:
            usable.append(float(row[metric.column]))
    if not usable:
        return Value(None, stubs[0] if stubs else "no row", len(selected))
    if metric.reduce == "sum":
        total = sum(usable)
        return Value(stats.Summary(total, total, total, len(usable)), None, len(selected))
    return Value(stats.summarize(usable), None, len(selected))


def table(rows, kind, metric, systems, profiles, group_label) -> list[list[str]]:
    out = []
    for group in groups(rows, kind, metric):
        line = [group_label(group[0], dict(zip(kind.variant_columns, group[1])))]
        for system in systems:
            line.append(format_value(value(rows, kind, metric, group, system, profiles[system]), metric))
        out.append(line)
    return out


def format_value(v: Value, metric: Metric) -> str:
    if v.summary is None:
        return v.stub or "no row"
    s = v.summary
    if metric.reduce == "sum" or s.low == s.high:
        return f"{s.median:,.{metric.digits}f}"
    return f"{s.median:,.{metric.digits}f} ({s.low:,.{metric.digits}f}-{s.high:,.{metric.digits}f})"


# ----------------------------------------------------------------- scoreboard


class Score(NamedTuple):
    metric: Metric
    group: str
    best: str | None
    best_value: float | None
    vtop: str  # formatted VTOP value, or its stub reason
    vtop_value: float | None
    ratio: float | None  # VTOP / best
    standing: str  # ahead, level, behind, or "no comparison"


def scoreboard(rows, kind, metrics: Sequence[Metric], systems: Sequence[str], profiles: dict[str, str],
               group_label) -> list[Score]:
    """One row per (metric, group), VTOP's included whatever its place."""
    out = []
    for metric in metrics:
        for group in groups(rows, kind, metric):
            label = group_label(group[0], dict(zip(kind.variant_columns, group[1])))
            values = {system: value(rows, kind, metric, group, system, profiles[system]) for system in systems}
            measured = {system: v.summary.median for system, v in values.items() if v.summary is not None}
            vtop = values.get("vtop")
            vtop_value = measured.get("vtop")
            if not measured:
                out.append(Score(metric, label, None, None, format_value(vtop, metric) if vtop else "no row",
                                 None, None, "no comparison"))
                continue
            pick = max if metric.better == "higher" else min
            best = pick(sorted(measured), key=lambda system: measured[system])
            ratio = None
            standing = "no comparison"
            if vtop_value is not None:
                best_value = measured[best]
                if best_value != 0:
                    ratio = vtop_value / best_value
                standing = _standing(metric, vtop_value, best_value, best == "vtop",
                                     {s: v for s, v in measured.items() if s != "vtop"})
            out.append(Score(metric, label, best, measured[best], format_value(vtop, metric) if vtop else "no row",
                             vtop_value, ratio, standing))
    return out


def _standing(metric: Metric, vtop: float, best: float, vtop_is_best: bool, others: dict[str, float]) -> str:
    if not others:
        return "no comparison"
    best_other = max(others.values()) if metric.better == "higher" else min(others.values())
    if vtop == best_other:
        return "level"
    scale = max(abs(vtop), abs(best_other))
    if scale and abs(vtop - best_other) / scale <= LEVEL_BAND:
        return "level"
    better = vtop > best_other if metric.better == "higher" else vtop < best_other
    return "ahead" if better else "behind"


def standing_sentences(scores: Sequence[Score], names: dict[str, str]) -> list[str]:
    """Where VTOP is behind, level and ahead, from the scoreboard rows only."""
    out = []
    for standing in ("behind", "level", "ahead"):
        picked = [s for s in scores if s.standing == standing]
        if not picked:
            out.append(f"VTOP is {standing} on no metric.")
            continue
        parts = []
        for s in picked:
            if standing == "ahead" or s.best == "vtop":
                parts.append(f"{s.metric.label}, {s.group} ({s.vtop})")
            else:
                parts.append(f"{s.metric.label}, {s.group} ({s.vtop} against {names.get(s.best, s.best)}'s "
                             f"{s.best_value:,.{s.metric.digits}f})")
        out.append(f"VTOP is {standing} on: " + "; ".join(parts) + ".")
    missing = [s for s in scores if s.standing == "no comparison"]
    if missing:
        out.append("No comparison (a system had no usable value): " +
                   "; ".join(f"{s.metric.label}, {s.group}" for s in missing) + ".")
    return out


# ------------------------------------------------------------------- footer


def footer_text(env: dict[str, Any], systems: Sequence[str], reg: dict[str, Any]) -> str:
    c = env["comparable"]
    versions = ", ".join(f"{registry.product(reg, s)['name']} {registry.product(reg, s)['version']}"
                         for s in systems if s != "vtop")
    lines = [
        f"host: {c.get('host_cpu')}, {c.get('host_logical_cpus')} logical CPUs, {c.get('host_os')} | "
        f"disk: {c.get('host_disk')} | Docker: {c.get('docker_platform')}, VM {c.get('docker_vm_cpus')} CPUs, "
        f"kernel {c.get('docker_vm_kernel')} | per tool: {c.get('tool_limits')}",
        f"VTOP: {str(c.get('vtop_commit'))[:12]} | {versions} | store: {env.get('store')} | host class: "
        f"{c.get('host_class')} | plan: {env['plan'].get('name')} | run: {env['run_id']} | "
        f"date: {env['started_at'][:10]} | single host, indicative, not a production benchmark",
    ]
    return "\n".join(lines)


def md_cell(text: str) -> str:
    flat = " ".join(str(text).split())
    for char in ("\\", "|", "`", "*", "_", "[", "]", "<", ">"):
        flat = flat.replace(char, "\\" + char)
    return flat


def md_table(header: Sequence[str], body: Sequence[Sequence[str]]) -> str:
    lines = ["| " + " | ".join(md_cell(h) for h in header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(md_cell(c) for c in line) + " |" for line in body]
    return "\n".join(lines)


# -------------------------------------------------------------------- charts


def setup_matplotlib(salt: str):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    matplotlib.rcdefaults()
    matplotlib.rcParams.update({
        "svg.hashsalt": salt, "svg.fonttype": "path", "font.family": "DejaVu Sans", "font.size": 9,
        "axes.edgecolor": GRID, "axes.linewidth": 0.8, "axes.labelcolor": INK_2, "axes.titlecolor": INK,
        "axes.titlesize": 10, "axes.facecolor": SURFACE, "figure.facecolor": SURFACE, "savefig.facecolor": SURFACE,
        "xtick.color": INK_2, "ytick.color": INK_2, "grid.color": GRID, "grid.linewidth": 0.8,
        "grid.linestyle": "-", "legend.frameon": False, "path.simplify": False,
    })
    return plt


def draw_chart(plt, chart: Chart, rows, kind, systems, profiles, names, group_label, footer: str,
               img_dir: str) -> list[str]:
    from kafka_compare import footer as kfooter

    palette = colours.series(colours_order(kind), systems)
    panels = len(chart.metrics)
    width, height = 7.5, 1.6 + 2.6 * panels
    fig = plt.figure(figsize=(width, height))
    fig.text(0.012, 1 - 0.18 / height, chart.title, fontsize=12.5, color=INK, ha="left", va="top")
    fig.text(0.012, 1 - 0.50 / height, chart.subtitle, fontsize=8, color=INK_2, ha="left", va="top")
    for index, metric in enumerate(chart.metrics):
        ax = fig.add_axes((0.09, 1 - (0.95 + 2.6 * (index + 1)) / height + 0.45 / height, 0.88,
                           2.0 / height))
        group_list = groups(rows, kind, metric)
        n = len(systems)
        bar = 0.8 / max(n, 1)
        top = 0.0
        stubs = []
        for gi, group in enumerate(group_list):
            for si, system in enumerate(systems):
                v = value(rows, kind, metric, group, system, profiles[system])
                x = gi + (si - (n - 1) / 2) * bar
                if v.summary is None:
                    stubs.append((x, v.stub))
                    continue
                s = v.summary
                ax.bar(x, s.median, bar * 0.92, color=palette[system], zorder=2)
                if s.low != s.high:
                    ax.plot([x, x], [s.low, s.high], color=INK, linewidth=0.9, zorder=3)
                ax.text(x, s.high, f"{s.median:,.{metric.digits}f}", ha="center", va="bottom", fontsize=6.5,
                        color=INK, zorder=4)
                top = max(top, s.high)
        stub_height = (top or 1.0) * 0.12
        for x, reason in stubs:
            ax.bar(x, stub_height, bar * 0.92, color="none", edgecolor=INK_2, hatch="///", linewidth=0.6, zorder=2)
            ax.text(x, stub_height, reason, ha="center", va="bottom", fontsize=6, color=INK_2, rotation=90)
        ax.set_xticks(range(len(group_list)))
        ax.set_xticklabels([group_label(g[0], dict(zip(kind.variant_columns, g[1]))) for g in group_list],
                           fontsize=7.5)
        ax.set_ylim(0, (top or 1.0) * 1.25)
        ax.set_ylabel(metric.label, fontsize=8)
        ax.grid(axis="y", zorder=0)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
        ax.tick_params(length=0)
        if index == 0:
            handles = [plt.Rectangle((0, 0), 1, 1, color=palette[s]) for s in systems]
            ax.legend(handles, [f"{names[s]} ({profiles[s]})" for s in systems], loc="upper left",
                      bbox_to_anchor=(0, 1.22), ncol=len(systems), fontsize=7.5)
    fig.text(0.012, 0.012, kfooter.wrap(footer, 150), fontsize=5.5, color=INK_2, ha="left", va="bottom")
    paths = []
    for ext in ("png", "svg"):
        path = os.path.join(img_dir, f"{chart.name}.{ext}")
        fig.savefig(path, dpi=150, metadata=kfooter.metadata(footer, ext))
        paths.append(path)
    plt.close(fig)
    return paths


def colours_order(kind: schema.Kind) -> list[str]:
    return registry.family_order(registry.load(), kind.family)


# --------------------------------------------------------------------- build


def build(run_dir: str, spec: Report, repo: str, *, doc_path: str | None = None,
          img_dir: str | None = None) -> list[str]:
    """Draw every chart and write the page; returns the paths written. RunRefused before anything is written."""
    kind = spec.kind
    reg = registry.load()
    rows, env = schema.load_run(run_dir, kind, registry=reg)
    plan = env["plan"]
    order = registry.family_order(reg, kind.family)
    systems = [s for s in order if s in plan["systems"]]
    profiles = {s: primary_profile(plan, s) for s in systems}
    names = {s: registry.product(reg, s)["name"] for s in systems}
    colours.series(order, systems)  # refuses an undrawable composition before anything is written
    doc_path = doc_path or os.path.join(repo, "docs", "benchmarks", f"{spec.doc_name}.md")
    img_dir = img_dir or os.path.join(repo, "docs", "benchmarks", spec.img_dir)
    footer = footer_text(env, systems, reg)
    metrics = [m for chart in spec.charts for m in chart.metrics]
    scores = scoreboard(rows, kind, metrics, systems, profiles, spec.group_label)
    plt = setup_matplotlib(f"vtop-{kind.name}-compare")
    os.makedirs(img_dir, exist_ok=True)
    os.makedirs(os.path.dirname(doc_path), exist_ok=True)
    written = []
    doc_dir = os.path.dirname(doc_path)
    sections = []
    for chart in spec.charts:
        written += draw_chart(plt, chart, rows, kind, systems, profiles, names, spec.group_label, footer, img_dir)
        image = os.path.relpath(os.path.join(img_dir, f"{chart.name}.png"), doc_dir)
        sections.append(f"## {chart.title}\n\n{chart.subtitle}\n\n![{chart.title}]({image})\n")
        for metric in chart.metrics:
            body = table(rows, kind, metric, systems, profiles, spec.group_label)
            sections.append(f"**{metric.label}** ({'sum over' if metric.reduce == 'sum' else 'median, min-max of'} "
                            "the repetitions)\n\n" + md_table(["cell"] + [names[s] for s in systems], body) + "\n")
    rel_csv = os.path.relpath(os.path.join(run_dir, f"{kind.name}.csv"), doc_dir)
    rel_env = os.path.relpath(os.path.join(run_dir, "environment.json"), doc_dir)
    score_rows = [[s.metric.label, s.group, names.get(s.best, "none") if s.best else "none",
                   "" if s.best_value is None else f"{s.best_value:,.{s.metric.digits}f}", s.vtop,
                   "" if s.ratio is None else f"{s.ratio:.2f}", s.standing] for s in scores]
    others = [r for r in rows if r["status"] != "ok"]
    other_rows = [[r["system"], r["profile"], r["cell"], r["repetition"], r["status"], r["note"]] for r in others]
    secondary = [f"{names[s]} `{p}`" for s in systems
                 for p in sorted({r["profile"] for r in rows if r["system"] == s}) if p != profiles[s]]
    text = [
        f"{GENERATED_MARK} from {rel_csv}. Do not edit; regenerate. -->",
        f"# {spec.title}",
        "",
        spec.intro,
        "",
        f"Run `{env['run_id']}`, host class `{env['comparable']['host_class']}`, plan `{plan.get('name')}`. "
        f"Data: [{os.path.basename(rel_csv)}]({rel_csv}), [environment.json]({rel_env}).",
        "",
        "## Where VTOP is behind, level and ahead",
        "",
        "Generated from the scoreboard below; \"level\" is within 5% of the best other system.",
        "",
        *[f"- {line}" for line in standing_sentences(scores, names)],
        "",
        "## Scoreboard",
        "",
        "Each system in its primary profile: " + ", ".join(f"{names[s]} `{profiles[s]}`" for s in systems) + "."
        + (" Other profiles (" + ", ".join(secondary) + ") are in the CSV and are not ranked." if secondary else ""),
        "",
        md_table(["metric", "cell", "best", "best value", "VTOP", "VTOP / best", "VTOP is"], score_rows),
        "",
        *sections,
    ]
    if other_rows:
        text += ["## Rows that are not ok", "",
                 md_table(["system", "profile", "cell", "rep", "status", "note"], other_rows), ""]
    if spec.notes:
        text += [spec.notes.strip(), ""]
    deviations = env.get("deviations") or []
    if deviations:
        text += ["## Deviations recorded by the run (rule 15)", "", *[f"- {md_cell(d)}" for d in deviations], ""]
    text += ["## Environment", "", "```", footer, "```", ""]
    with open(doc_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(text))
    written.append(doc_path)
    return written

# ---------------------------------------------------------------------- loading


class Measured(NamedTuple):
    """One kind with a committed run: everything its charts and tables are drawn from."""

    name: str
    spec: Any  # compare_common.report.Report
    run_dir: str
    rows: list[dict[str, str]]
    env: dict[str, Any]
    systems: list[str]
    profiles: dict[str, str]
    names: dict[str, str]
    footer: str


def report_spec(kind: str):
    import importlib

    return importlib.import_module(f"{kind}_compare.report").REPORT


def metric_of(spec: Any, metric_id: str) -> creport.Metric:
    for chart in spec.charts:
        for metric in chart.metrics:
            if metric.id == metric_id:
                return metric
    raise KeyError(f"the {spec.kind.name} report has no metric {metric_id!r}")


def load(kind: str, run_dir: str, reg: dict[str, Any]) -> Measured:
    """The run, or `schema.RunRefused` (nothing is written before that)."""
    spec = report_spec(kind)
    rows, env = schema.load_run(run_dir, spec.kind, registry=reg)
    order = registry.family_order(reg, spec.kind.family)
    systems = [s for s in order if s in env["plan"]["systems"]]
    profiles = {s: creport.primary_profile(env["plan"], s) for s in systems}
    names = {s: registry.product(reg, s)["name"] for s in systems}
    return Measured(kind, spec, run_dir, rows, env, systems, profiles, names,
                    creport.footer_text(env, systems, reg, rows))


def expected_systems(kind: str, reg: dict[str, Any]) -> list[str]:
    spec = report_spec(kind)
    return [s for s in registry.family_order(reg, spec.kind.family) if s in spec.kind.profiles]


def check_summary_spec() -> None:
    """Every chart names a kind and metrics that exist, and every use case is the one its kind measures."""
    problems = []
    names = set()
    for case in USE_CASES:
        for chart in case.charts:
            if chart.name in names:
                problems.append(f"chart {chart.name} is declared twice")
            names.add(chart.name)
            if chart.kind not in KIND_ORDER:
                problems.append(f"{chart.name}: unknown kind {chart.kind!r}")
                continue
            spec = report_spec(chart.kind)
            if case.id not in spec.kind.use_cases:
                problems.append(f"{chart.name}: the {chart.kind} kind does not measure use case ({case.id})")
            for metric_id in chart.metrics:
                try:
                    metric_of(spec, metric_id)
                except KeyError as exc:
                    problems.append(f"{chart.name}: {exc.args[0]}")
    if problems:
        raise schema.RunRefused("the summary's own chart list is wrong: " + "; ".join(problems))


# ------------------------------------------------------------------------ pieces


def _fmt(v: creport.Value, metric: creport.Metric) -> str:
    if v.summary is None and v.stub in ("no row", "not measured"):
        return NOT_MEASURED
    return creport.format_value(v, metric)


def metric_table(m: Measured, metric: creport.Metric) -> str:
    kind = m.spec.kind
    extra = creport.secondary_columns(m.rows, m.systems, m.profiles)
    header = ["cell"] + [m.names[s] for s in m.systems] + [f"{m.names[s]} {p} (secondary)" for s, p in extra]
    body = []
    for group in creport.groups(m.rows, kind, metric):
        line = [m.spec.group_label(group[0], dict(zip(kind.variant_columns, group[1])))]
        for system in m.systems:
            line.append(_fmt(creport.value(m.rows, kind, metric, group, system, m.profiles[system]), metric))
        for system, profile in extra:
            line.append(_fmt(creport.value(m.rows, kind, metric, group, system, profile), metric))
        body.append(line)
    how = "sum over" if metric.reduce == "sum" else "median, min-max of"
    return f"**{creport.md_cell(metric.label)}** ({how} the repetitions)\n\n" + creport.md_table(header, body)


def unmeasured_table(kind: str, metric_ids: Sequence[str], reg: dict[str, Any]) -> str:
    spec = report_spec(kind)
    systems = expected_systems(kind, reg)
    header = ["metric", "cells"] + [registry.product(reg, s)["name"] for s in systems]
    body = []
    for metric_id in metric_ids:
        metric = metric_of(spec, metric_id)
        body.append([metric.label, ", ".join(metric.cells)] + [NOT_MEASURED] * len(systems))
    return creport.md_table(header, body)


def score_rows(scores: Sequence[creport.Score], names: Mapping[str, str]) -> list[list[str]]:
    return [[s.metric.label, s.group, names.get(s.best, "none") if s.best else "none",
             "" if s.best_value is None else f"{s.best_value:,.{s.metric.digits}f}", s.vtop,
             "" if s.ratio is None else f"{s.ratio:.2f}", s.standing] for s in scores]


def source_line(m: Measured, doc_dir: str) -> str:
    c = m.env["comparable"]
    csv_rel = os.path.relpath(os.path.join(m.run_dir, f"{m.spec.kind.name}.csv"), doc_dir)
    return (f"Source: `{m.env['run_id']}` ([{os.path.basename(csv_rel)}]({csv_rel})), the `{m.name}` kind, plan "
            f"`{m.env['plan'].get('name')}`, host class `{c.get('host_class')}`, {m.env['started_at'][:10]}, "
            f"VTOP `{str(c.get('vtop_commit'))[:12]}`.")


def chart_spec(chart: SummaryChart, m: Measured) -> creport.Chart:
    return creport.Chart(chart.name, chart.title, chart.subtitle,
                         tuple(metric_of(m.spec, metric_id) for metric_id in chart.metrics))


def kind_page(kind: str) -> str:
    return f"{report_spec(kind).doc_name}.md"


# ------------------------------------------------------------------------- build


def build(runs: Mapping[str, str], repo: str, *, doc_path: str | None = None,
          img_dir: str | None = None) -> list[str]:
    """Write the page, and a chart for every summary chart whose kind has a run; the paths written.

    `runs` maps a kind to the directory of its (one) run; a kind missing from it is not measured yet.
    RunRefused, before anything is written, for a run the loader refuses or a kind it does not know.
    """
    reg = registry.load()
    registry.check(reg)
    check_summary_spec()
    unknown = sorted(set(runs) - set(KIND_ORDER))
    if unknown:
        raise schema.RunRefused(f"no summary for kind(s) {unknown}; the summary knows {list(KIND_ORDER)}")
    doc_path = doc_path or os.path.join(repo, DOC_REL)
    img_dir = img_dir or os.path.join(repo, IMG_REL)
    doc_dir = os.path.dirname(doc_path)
    measured = {kind: load(kind, runs[kind], reg) for kind in KIND_ORDER if kind in runs}

    plt = None
    written: list[str] = []
    if measured:
        os.makedirs(img_dir, exist_ok=True)
        plt = creport.setup_matplotlib("vtop-summary")

    scores_by_case: dict[str, dict[str, list[creport.Score]]] = {}
    case_sections: list[str] = []
    for case in USE_CASES:
        parts = [f"## ({case.id}) {case.title}", "", case.question, ""]
        for chart in case.charts:
            m = measured.get(chart.kind)
            if m is None:
                parts += [f"### {chart.title}", "", chart.subtitle, "",
                          f"{NOT_MEASURED.capitalize()}: no committed `{chart.kind}` run yet. Every cell below is "
                          "empty until one is committed; nothing is drawn and no number is implied.", "",
                          unmeasured_table(chart.kind, chart.metrics, reg), ""]
                continue
            drawn = chart_spec(chart, m)
            written += creport.draw_chart(plt, drawn, m.rows, m.spec.kind, m.systems, m.profiles, m.names,
                                          m.spec.group_label, m.footer, img_dir)
            image = os.path.relpath(os.path.join(img_dir, f"{chart.name}.png"), doc_dir)
            parts += [f"### {chart.title}", "", chart.subtitle, "", f"![{chart.title}]({image})", "",
                      source_line(m, doc_dir), ""]
            for metric in drawn.metrics:
                parts += [metric_table(m, metric), ""]
            scores = creport.scoreboard(m.rows, m.spec.kind, list(drawn.metrics), m.systems, m.profiles,
                                        m.spec.group_label)
            scores_by_case.setdefault(case.id, {}).setdefault(chart.kind, []).extend(scores)
            parts += ["Scoreboard (each system in its primary profile; VTOP's row is always present):", "",
                      creport.md_table(["metric", "cell", "best", "best value", "VTOP", "VTOP / best", "VTOP is"],
                                       score_rows(scores, m.names)), ""]
        case_sections.append("\n".join(parts))

    text = [
        f"{GENERATED_MARK} from the committed runs under benchmarks/<kind>_compare/results/. "
        "Do not edit; regenerate. -->",
        "# VTOP against other telemetry and archive products",
        "",
        "How does VTOP's actual job, archiving telemetry to object storage under the commit rule (a source's "
        "progress moves only after the object is stored and verified), compare with the other products people "
        "use for it, per use case? Every figure on this page is generated from a committed run's CSV, and "
        "where VTOP is behind the page says so from the scoreboard rows, not from prose. VTOP's licence is "
        f"{registry.product(reg, 'vtop')['licence']}; each comparand's licence, version and the evidence it "
        "may be published under are in the [products table](#products-versions-and-licences).",
        "",
        "## What is measured yet",
        "",
        _status_table(measured, doc_dir, reg),
        "",
        "## Where VTOP is behind, level and ahead",
        "",
        *_standing_section(scores_by_case, measured),
        "",
        *case_sections,
        "## Products, versions and licences",
        "",
        _products_table(measured, reg),
        "",
        "## Fairness rules",
        "",
        "Rules 1 to 10 are the Kafka comparison's (#595) with \"Kafka\" read as \"every other product\"; rules 11 "
        "to 21 are this comparison's (#744). Each run's report records how it kept them.",
        "",
        *[f"{n}. {rule}" for n, rule in RULES],
        "",
        "## Limits of this evidence",
        "",
        *[f"- {limit}" for limit in LIMITS],
        *_run_limits(measured),
        "",
        "## Regenerating this page",
        "",
        "```",
        "python3 -m pip install --require-hashes -r benchmarks/kafka_compare/requirements-report.txt",
        "python3 benchmarks/compare_common/regenerate.py",
        "```",
        "",
        "The page and its charts are rewritten from the committed runs, and CI fails when they differ from "
        "what the committed CSVs produce.",
        "",
    ]
    os.makedirs(doc_dir, exist_ok=True)
    with open(doc_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(text))
    written.append(doc_path)
    return written


def _status_table(measured: Mapping[str, Measured], doc_dir: str, reg: dict[str, Any]) -> str:
    body = []
    for kind in KIND_ORDER:
        spec = report_spec(kind)
        cases = ", ".join(f"({c})" for c in spec.kind.use_cases)
        m = measured.get(kind)
        if m is None:
            body.append([kind, cases, NOT_MEASURED, "", "", "", ""])
            continue
        c = m.env["comparable"]
        body.append([kind, cases, f"`{m.env['run_id']}`", str(c.get("host_class")), str(m.env["plan"].get("name")),
                     m.env["started_at"][:10], f"[full report]({kind_page(kind)})"])
    return creport.md_table(["comparison", "use cases", "run", "host class", "plan", "date", "page"], body)


def _standing_section(scores_by_case: Mapping[str, Mapping[str, list[creport.Score]]],
                      measured: Mapping[str, Measured]) -> list[str]:
    if not measured:
        return ["Nothing is measured yet, so this page makes no claim about VTOP. It is filled from the "
                "scoreboard of each use case as soon as a run is committed."]
    out = ["Generated from the scoreboards below; \"level\" is within 5% of the best other system.", ""]
    for case in USE_CASES:
        by_kind = scores_by_case.get(case.id)
        if not by_kind:
            out.append(f"- **({case.id}) {case.title}**: {NOT_MEASURED}.")
            continue
        out.append(f"- **({case.id}) {case.title}**")
        for kind, scores in by_kind.items():
            names = measured[kind].names
            out += [f"    - {kind}: {line}" for line in creport.standing_sentences(scores, names)]
    return out


def _products_table(measured: Mapping[str, Measured], reg: dict[str, Any]) -> str:
    seen: list[str] = []
    cases: dict[str, set[str]] = {}
    for kind in KIND_ORDER:
        spec = report_spec(kind)
        for system in expected_systems(kind, reg):
            if system not in seen:
                seen.append(system)
            cases.setdefault(system, set()).update(spec.kind.use_cases)
    seen.append("kafka")  # the source of every archive run
    cases["kafka"] = {"a"}
    body = []
    for system in seen:
        p = registry.product(reg, system)
        recorded = sorted({v for m in measured.values() for v in creport.recorded_versions(m.rows, system)})
        commits = sorted({str(m.env["comparable"].get("vtop_commit"))[:12] for m in measured.values()})
        if system == "vtop":
            version = ", ".join(f"commit {c}" for c in commits) if commits else "commit under test"
        elif recorded:
            version = ", ".join(recorded)
        else:
            version = f"{p['version']} (pinned, not run yet)"
        profiles = sorted({m.profiles[system] for m in measured.values() if system in m.profiles})
        body.append([p["name"], p["role"], p["licence"], version, ", ".join(f"`{x}`" for x in profiles) or "",
                     ", ".join(f"({c})" for c in sorted(cases[system])),
                     f"[licence]({p['evidence_url']}), read {p['retrieved']}; publish_ok {str(p['publish_ok']).lower()}"
                     ])
    return creport.md_table(["product", "role", "licence", "version", "profile drawn (what its commit means)",
                             "use cases", "evidence"], body)


def _run_limits(measured: Mapping[str, Measured]) -> list[str]:
    out = []
    for kind in KIND_ORDER:
        m = measured.get(kind)
        if m is None:
            continue
        c = m.env["comparable"]
        out.append(f"- **The `{kind}` run:** plan `{m.env['plan'].get('name')}`, host class "
                   f"`{c.get('host_class')}`, store {m.env.get('store')}, host {c.get('host_cpu')} "
                   f"({c.get('host_logical_cpus')} logical CPUs), per tool {c.get('tool_limits')}.")
    return out



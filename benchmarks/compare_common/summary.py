def committed_runs_by_kind(repo: str = REPO) -> dict[str, str]:
    """{kind: its committed run}; more than one run of a kind is refused (each writes one page)."""
    from compare_common import regenerate

    out = {}
    for kind in KIND_ORDER:
        found = regenerate.committed_runs(kind, repo)
        if len(found) > 1:
            names = ", ".join(os.path.basename(r) for r in found)
            raise schema.RunRefused(f"{len(found)} committed {kind} runs ({names}); the summary draws one per "
                                    "kind, and the kind's own page can show only one")
        if found:
            out[kind] = found[0]
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run", action="append", default=[], metavar="KIND=DIR",
                        help="a run to draw for a kind; default: every kind's committed run")
    parser.add_argument("--doc", default=None)
    parser.add_argument("--img-dir", default=None)
    args = parser.parse_args(argv)
    try:
        if args.run:
            runs = {}
            for item in args.run:
                kind, sep, directory = item.partition("=")
                if not sep or not kind or not directory:
                    raise schema.RunRefused(f"--run {item!r} is not KIND=DIR")
                if kind in runs:
                    raise schema.RunRefused(f"--run names the {kind} kind twice")
                runs[kind] = directory
        else:
            runs = committed_runs_by_kind()
        written = build(runs, REPO, doc_path=args.doc, img_dir=args.img_dir)
    except (schema.RunRefused, registry.RegistryError) as exc:
        print(f"summary refused: {exc}", file=sys.stderr)
        return 2
    for path in written:
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())

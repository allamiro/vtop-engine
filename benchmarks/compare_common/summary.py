#!/usr/bin/env python3
"""The cross-product summary: docs/benchmarks/comparison-summary.md and its bar charts (#744 section 5).

    python3 -m pip install --require-hashes -r benchmarks/kafka_compare/requirements-report.txt
    python3 benchmarks/compare_common/summary.py            # every committed run, as HEAD has them
    python3 benchmarks/compare_common/summary.py --run archive=benchmarks/archive_compare/results/<run-id>

One page for the question #744 asks: how does VTOP's actual job, archiving
telemetry to object storage under the commit rule, compare with the other
products that do it. For each use case (a to e) it draws the headline metrics
of the comparison kind that measures it (throughput, gaps and duplicates after
a kill -9, what the verification does and costs, CPU-seconds and store requests
per GiB, bytes on the wire), from the committed run of that kind, each chart
beside a table of the same numbers, a scoreboard in which VTOP's row is present
whatever its place, and the run it came from (id, host class, plan, date, tool
versions, config hashes, licences). It also states the 21 fairness rules and
the limits of the evidence.

It works with nothing measured, with some kinds measured and with all of them:
a kind with no committed run is "not measured yet" in every one of its cells,
with no chart and no number, and a cell where a tool failed or was not
sustained is the report's hatched stub, never a missing bar. Every figure comes
from a run's CSV (#595 rule 9); the registry (`products.toml`) supplies each
product's licence, version and evidence. A run `schema.load_run` refuses
(unfinished, partial, mixed, private, a performance row from a hosted runner)
is refused here too, exit 2, with nothing written.

The per-kind pages (`<kind>-comparison.md`) stay the full reports; this page
repeats none of their prose, only the headline charts, and links to them.
"""

"""The crash run's report (#599, #600): tables, charts, refusals and the drift-free output.

Two runs feed it. `fixtures/crash-smoke` is what the crash harness wrote on its smoke run (2 crashes per
configuration and mode on a 4-vCPU VM, `environment.json` without its Compose texts): real numbers, real
refused-and-failed rows, too few crashes to commit. `synthetic_run` builds a 12-crash run of the shape the AWS
round writes (power loss only) from the same rows, so the report's default floor of ok crashes holds.
The loader is `crash_schema` (the harness's own), whose refusals are pinned by test_kafka_compare_crash.py.
"""
import csv
import json
import os

import pytest

pytest.importorskip("matplotlib")
Image = pytest.importorskip("PIL.Image")

from kafka_compare import colours, crash_report, schema  # noqa: E402
from kafka_compare import crash_schema as cs  # noqa: E402
from kafka_compare import report as kreport  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
SMOKE = os.path.join(HERE, "fixtures", "crash-smoke")


def read_rows(run_dir):
    with open(os.path.join(run_dir, "crash.csv"), newline="") as handle:
        return list(csv.DictReader(handle))


def synthetic_run(directory, crashes=12, modes=("flakey-drop",), kafka_defaults_loses=True, refuse=()):
    """A complete run of the AWS round's shape. Kafka's defaults lose records in every power-loss crash, the
    fsync-parity configuration and VTOP lose none. `refuse` is a set of (config, crash) written as refused."""
    with open(os.path.join(SMOKE, "environment.json")) as handle:
        env = json.load(handle)
    env["matrix"].update(crashes=crashes, crash_modes=list(modes), smoke=False)
    env["run_id"] = "crash-synthetic"
    env["run_state"] = "complete"
    fingerprint = schema.fingerprint(env)
    template = {(r["config"], r["crash_mode"]): r for r in read_rows(SMOKE) if r["status"] == "ok"}
    rows = []
    for config in env["matrix"]["configs"]:
        for mode in modes:
            for crash in range(1, crashes + 1):
                row = dict(template[(config, mode)])
                acked = 9000 + 37 * crash
                row.update(run_id=env["run_id"], env_fingerprint=fingerprint, crash=str(crash), acked=str(acked),
                           kill_to_drop_ms=row["kill_to_drop_ms"] and str(120 + crash))
                if config == "kafka-defaults" and mode == "flakey-drop" and kafka_defaults_loses:
                    row.update(acked_lost=str(4000 + 211 * crash), lost_first_seq="1", lost_last_seq="2",
                               lost_runs="1", lost_window_s="5.5")
                elif row["acked_lost"] != "0":
                    row.update(acked_lost="0", lost_first_seq="", lost_last_seq="", lost_runs="0", lost_window_s="")
                if (config, crash) in refuse and mode == "flakey-drop":
                    row.update(status="refused", acked_lost="", lost_first_seq="", lost_last_seq="",
                               canary_unsynced_lost="false",
                               note="the unsynced canary survived whole: the crash did not drop the page cache")
                rows.append(row)
    os.makedirs(directory)
    with open(os.path.join(directory, "environment.json"), "w") as handle:
        json.dump(env, handle)
    path = os.path.join(directory, "crash.csv")
    cs.write_header(path)
    cs.append_rows(path, rows)
    return str(directory)


def render(run_dir, tmp_path, name="out", **kw):
    img, doc = tmp_path / name / "img", tmp_path / name / "kafka-crash.md"
    written = crash_report.build(run_dir, str(img), str(doc), kreport._setup_matplotlib, **kw)
    return written, img, doc


# ------------------------------------------------------------------------------ the smoke run


def test_the_smoke_run_renders_both_charts_and_a_page_with_the_tables(tmp_path):
    written, img, doc = render(SMOKE, tmp_path, min_ok=1)
    assert sorted(os.path.basename(p) for p in written) == [
        "kafka-crash-drop-gap.png", "kafka-crash-drop-gap.svg", "kafka-crash-loss.png", "kafka-crash-loss.svg",
        "kafka-crash.md"]
    page = doc.read_text()
    assert page.startswith("<!-- Generated by benchmarks/kafka_compare/crash_report.py")
    # Kafka's defaults lost acknowledged records in both power-loss crashes: 6,857 + 4,715, from crash.csv.
    assert "| Kafka, defaults | flakey-drop | 2 of 2 | 19,710 | **11,572** | 2 of 2 | 5,786 | 6,857 | - |" in page
    # Fsync on every message lost nothing in 2 crashes, and the bound says how little 2 crashes show.
    assert "| Kafka, fsync on every message | flakey-drop | 2 of 2 | 19,723 | **0** | 0 of 2 | - | 0 | 77.6 % |" in page
    # VTOP's second power-loss crash and first process-kill crash did not serve after the restart: failed rows.
    assert "| VTOP, as shipped | flakey-drop | 1 of 2 |" in page
    assert "## Crashes that are not ok" in page and "**failed**" in page
    # Every crash is a row of the last table, refused and failed ones included.
    every = page.split("## Every crash", 1)[1].split("## Crashes that are not ok", 1)[0]
    assert sum(1 for line in every.splitlines() if line.startswith("| ") and "---" not in line) == 12 + 1
    assert "sentinel needed" in page and "kill to drop, ms" in page


def test_the_default_floor_refuses_a_short_run_by_name_and_writes_nothing(tmp_path, capsys):
    out = tmp_path / "out"
    code = kreport.main([SMOKE, "--img-dir", str(out / "img"), "--doc", str(out / "kafka-crash.md")])
    assert code == 2
    err = capsys.readouterr().err
    assert "report refused" in err and "at least 10" in err and "kafka-defaults" in err
    assert not out.exists()


def test_a_crash_directory_goes_to_the_crash_report_and_prints_what_it_wrote(tmp_path, capsys):
    out = tmp_path / "out"
    assert kreport.main([SMOKE, "--img-dir", str(out / "img"), "--doc", str(out / "kafka-crash.md"),
                         "--min-ok", "1"]) == 0
    printed = capsys.readouterr().out.split()
    assert str(out / "kafka-crash.md") in printed and str(out / "img" / "kafka-crash-loss.svg") in printed
    assert kreport.DEFAULT_CRASH_DOC.endswith(os.path.join("docs", "benchmarks", "kafka-crash.md"))


# ------------------------------------------------------------------------ the run the AWS round writes


def test_a_twelve_crash_run_loads_at_the_default_floor_and_prints_the_bound(tmp_path):
    run = synthetic_run(tmp_path / "run")
    _written, _img, doc = render(run, tmp_path)
    page = doc.read_text()
    # 0 of 12: 1 - 0.05 ** (1 / 12) = 22.1 %.
    assert "| Kafka, fsync on every message | flakey-drop | 12 of 12 |" in page and "| 0 of 12 | - | 0 | 22.1 % |" in page
    assert "| Kafka, defaults | flakey-drop | 12 of 12 |" in page and "| 12 of 12 |" in page
    assert "bounded to 22.1 % at 95 %" in page
    # Power loss only: the control's rows and panel are absent, and so is nothing else the plan wrote.
    assert "sigkill" not in page.split("## Limits", 1)[0].split("## Every crash", 1)[1]
    assert "bound" in page and "SIGKILL of all three nodes, page cache kept" not in page


def test_a_refused_crash_is_a_row_with_its_reason_and_is_not_counted_as_ok(tmp_path):
    run = synthetic_run(tmp_path / "run", refuse={("vtop-shipped", 3), ("vtop-shipped", 4)})
    _written, _img, doc = render(run, tmp_path)
    page = doc.read_text()
    assert "| VTOP, as shipped | flakey-drop | 10 of 12 |" in page
    assert "| 0 of 10 | - | 0 | 25.9 % |" in page  # the bound is computed over the 10 ok crashes
    assert "`vtop-shipped` / `flakey-drop` / crash 3: **refused**" in page
    assert "the unsynced canary survived whole" in page


def test_a_run_whose_kafka_defaults_lost_nothing_is_called_suspect_on_the_page(tmp_path):
    run = synthetic_run(tmp_path / "run", kafka_defaults_loses=False)
    page = render(run, tmp_path)[2].read_text()
    assert "The method is suspect" in page and "dm-flakey" in page


def test_both_modes_draw_two_panels_and_the_control_rows(tmp_path):
    run = synthetic_run(tmp_path / "run", modes=("flakey-drop", "sigkill"))
    _written, _img, doc = render(run, tmp_path)
    page = doc.read_text()
    assert "| Kafka, defaults | sigkill | 12 of 12 |" in page


def test_a_partial_run_is_refused_through_the_report_with_nothing_written(tmp_path, capsys):
    run = synthetic_run(tmp_path / "run")
    path = os.path.join(run, "crash.csv")
    rows = read_rows(run)
    kept = [r for r in rows if not (r["config"] == "vtop-shipped" and int(r["crash"]) > 6)]
    with open(path, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=cs.COLUMNS)
        writer.writeheader()
        writer.writerows(kept)
    out = tmp_path / "out"
    assert kreport.main([run, "--img-dir", str(out / "img"), "--doc", str(out / "p.md")]) == 2
    assert "partial" in capsys.readouterr().err and not out.exists()


# --------------------------------------------------------------------------------- the images


def test_the_systems_are_drawn_in_the_registry_s_colours_and_the_footer_is_in_the_metadata(tmp_path):
    run = synthetic_run(tmp_path / "run")
    _written, img, _doc = render(run, tmp_path)
    svg = (img / "kafka-crash-loss.svg").read_text()
    assert colours.colour("kafka", "light") in svg and colours.colour("vtop", "light") in svg
    for name in ("kafka-crash-loss", "kafka-crash-drop-gap"):
        footer_in_svg = (img / f"{name}.svg").read_text()
        assert "crash-synthetic" in footer_in_svg  # the Description metadata
        with Image.open(img / f"{name}.png") as picture:
            description = picture.info["Description"]
        assert "run: crash-synthetic" in description and "crashes: 12 per configuration and mode" in description
        assert "disk:" in description and "VTOP:" in description and "Kafka:" in description


def test_the_output_is_deterministic(tmp_path):
    run = synthetic_run(tmp_path / "run")
    _a, img_a, doc_a = render(run, tmp_path, "a")
    _b, img_b, doc_b = render(run, tmp_path, "b")
    assert doc_a.read_bytes() == doc_b.read_bytes()
    for name in sorted(os.listdir(img_a)):
        if name.endswith(".svg"):
            assert (img_a / name).read_bytes() == (img_b / name).read_bytes()


def test_the_fixture_run_is_the_harness_s_own_not_hand_edited():
    # A guard on the fixture: it loads as a complete crash run and says what the harness measured.
    run = cs.load_crash_run(SMOKE)
    assert run.environment["kind"] == "crash" and run.environment["run_state"] == "complete"
    assert len(run.rows) == 12 and run.environment["matrix"]["crashes"] == 2

"""s3_compat_report.py: every cell of the S3 compatibility page comes from a recorded outcome (#722)."""
import json
import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import s3_compat_report as report  # noqa: E402


def case(name, caps, outcome, expectation="pass", deciding=None, expected=True, method=None, server="srv"):
    return {
        "server": server,
        "case": name,
        "capabilities": caps,
        "deciding_capability": deciding,
        "expectation": expectation,
        "outcome": outcome,
        "expected": expected,
        "method": method,
        "seconds": 0.1,
    }


def write_repo(tmp_path, runs, servers=None, digests=None, readme="intro\n<!-- s3-compat:start -->\nold\n<!-- s3-compat:end -->\nrest\n"):
    (tmp_path / report.RESULTS).mkdir(parents=True)
    (tmp_path / report.SERVERS).mkdir(parents=True)
    for run in runs:
        (tmp_path / report.RESULTS / f"{run['server']}.json").write_text(json.dumps(run))
    for sid, text in (servers or {}).items():
        (tmp_path / report.SERVERS / f"{sid}.yaml").write_text(text)
    for server, digest in (digests or {}).items():
        d = tmp_path / report.COMPOSE / server
        d.mkdir(parents=True)
        image = "build: ../x\n    image: local:1" if digest is None else f"image: x/y:1@{digest}"
        (d / "compose.yml").write_text(f"services:\n  server:\n    {image}\n")
    (tmp_path / "README.md").write_text(readme)
    return str(tmp_path)


def run(server, cases, digest=None):
    return {
        "server": server,
        "server_version": "1.0",
        "image_digest": digest,
        "vtop_commit": "0123456789abcdef",
        "run_date": "2026-11-14",
        "cases": [dict(c, server=server) for c in cases],
    }


def test_a_capability_no_case_named_is_not_tested_never_passed():
    assert report.cell([case("a", ["put_get_head"], "pass")], "object_lock") == report.NOT_TESTED


def test_a_refusal_is_shown_as_refused_as_designed_for_the_capability_that_decided_it():
    cases = [case("lock", ["versioning", "object_lock"], "refused", "unsupported (refused at startup)", "object_lock")]
    assert report.cell(cases, "object_lock") == report.REFUSED
    # Versioning did not decide the case and was not exercised: not tested.
    assert report.cell(cases, "versioning") == report.NOT_TESTED


def test_a_capability_the_file_says_the_server_lacks_is_refused_when_a_refusal_case_named_it():
    # Garage lacks both; the case records the one that decided it (object_lock),
    # and the file says versioning is unsupported too: that refusal is shown for it.
    cases = [case("lock", ["object_lock", "versioning"], "refused", "unsupported (refused at startup)", "object_lock")]
    assert report.cell(cases, "versioning", "unsupported") == report.REFUSED
    # A file that says the server has it does not turn a refusal into a refused cell.
    assert report.cell(cases, "versioning", "pass") == report.NOT_TESTED
    assert report.state_of({"state": "unsupported", "refusal": "startup"}) == "unsupported"
    assert report.state_of("pass") == "pass"
    assert report.state_of(None) is None


def test_an_unexpected_outcome_marks_every_capability_of_the_case():
    cases = [case("m", ["multipart", "path_style"], "unexpected_fail", expected=False)]
    assert report.cell(cases, "multipart") == report.UNEXPECTED
    assert report.cell(cases, "path_style") == report.UNEXPECTED


def test_a_case_the_harness_could_not_run_tested_nothing():
    cases = [case("m", ["multipart", "virtual_host"], "not_run")]
    assert report.cell(cases, "multipart") == report.NOT_TESTED


def test_xfail_and_unknown_are_labelled_as_what_they_are():
    xfail = [case("c", ["conditional_put"], "fail", "xfail (#9)", "conditional_put")]
    assert report.cell(xfail, "conditional_put") == "known failure (#9)"
    unknown = [case("e", ["checksum_sha256_enforced"], "fail", "unknown", "checksum_sha256_enforced")]
    assert report.cell(unknown, "checksum_sha256_enforced") == report.UNKNOWN_FAILED
    unknown[0]["outcome"] = "pass"
    assert report.cell(unknown, "checksum_sha256_enforced") == report.UNKNOWN_PASSED


def test_the_page_and_readme_are_generated_and_the_check_catches_drift(tmp_path):
    digest = "sha256:" + "a" * 64
    repo = write_repo(
        tmp_path,
        [run("srv", [case("v", ["put_get_head", "path_style"], "pass", method="store_checksum")], digest)],
        {"srv": "id: srv\nname: Server One\ngating: false\ncapabilities: {}\n"},
        digests={"srv": digest},
    )
    assert report.main(["--repo", repo]) == 0
    page = (tmp_path / report.PAGE).read_text()
    assert page.startswith("<!-- Generated by scripts/s3_compat_report.py")
    assert "| `put_get_head` | tested: pass |" in page
    assert "| `object_lock` | not tested |" in page
    assert "`store_checksum`" in page
    readme = (tmp_path / "README.md").read_text()
    assert "against: Server One." in readme and readme.startswith("intro\n") and readme.endswith("rest\n")
    assert report.main(["--repo", repo, "--check"]) == 0
    (tmp_path / report.PAGE).write_text(page + "hand edit\n")
    assert report.main(["--repo", repo, "--check"]) == 1


def test_results_from_another_image_than_the_pinned_one_fail_the_check(tmp_path, capsys):
    repo = write_repo(
        tmp_path,
        [run("srv", [case("v", ["put_get_head"], "pass")], "sha256:" + "b" * 64)],
        digests={"srv": "sha256:" + "c" * 64},
    )
    assert report.main(["--repo", repo]) == 0
    assert report.main(["--repo", repo, "--check"]) == 1
    assert "the results are stale" in capsys.readouterr().err


def test_a_built_image_is_not_held_to_a_digest(tmp_path):
    # The lab's MinIO is built from a commit-pinned Dockerfile: its results
    # carry the local image id, which no compose file can pin.
    repo = write_repo(
        tmp_path,
        [run("minio", [case("v", ["put_get_head"], "pass")], "sha256:" + "d" * 64)],
        digests={"minio": None},
    )
    assert report.main(["--repo", repo]) == 0
    assert report.main(["--repo", repo, "--check"]) == 0


def test_ingest_turns_a_runs_lines_into_committed_results(tmp_path, monkeypatch):
    repo = write_repo(tmp_path, [])
    upload = tmp_path / "artifacts" / "s3-compat-results-srv"
    upload.mkdir(parents=True)
    lines = [
        dict(case("b", ["put_get_head"], "pass"), server_version="1.0", image_digest="sha256:" + "e" * 64, vtop_commit="abc"),
        dict(case("a", ["multipart"], "pass"), server_version="1.0", image_digest="sha256:" + "e" * 64, vtop_commit="abc"),
    ]
    (upload / "results-srv.jsonl").write_text("".join(json.dumps(line) + "\n" for line in lines))
    monkeypatch.setenv("S3_COMPAT_RUN_DATE", "2026-11-15")
    assert report.main(["--repo", repo, "--ingest", str(tmp_path / "artifacts")]) == 0
    committed = json.loads((tmp_path / report.RESULTS / "srv.json").read_text())
    assert committed["run_date"] == "2026-11-15"
    assert committed["server_version"] == "1.0" and committed["vtop_commit"] == "abc"
    assert [c["case"] for c in committed["cases"]] == ["a", "b"]
    assert "| `multipart` | tested: pass |" in (tmp_path / report.PAGE).read_text()


def test_a_server_with_an_unexpected_outcome_is_not_named_in_the_readme(tmp_path):
    repo = write_repo(tmp_path, [run("srv", [case("v", ["put_get_head"], "unexpected_fail", expected=False)])])
    assert report.main(["--repo", repo]) == 0
    assert "No S3 server's committed live-test results are all as expected" in (tmp_path / "README.md").read_text()


@pytest.mark.parametrize(
    "mutate, message",
    [
        (lambda r: r.update(server="other"), "does not match the file name"),
        (lambda r: r["cases"][0].update(outcome="passed"), "has outcome"),
        (lambda r: r["cases"][0].update(capabilities=["object_locks"]), "names capability"),
        (lambda r: r.update(run_date="yesterday"), "run_date"),
    ],
)
def test_malformed_results_are_refused(tmp_path, capsys, mutate, message):
    r = run("srv", [case("v", ["put_get_head"], "pass")])
    mutate(r)
    (tmp_path / report.RESULTS).mkdir(parents=True)
    (tmp_path / report.RESULTS / "srv.json").write_text(json.dumps(r))
    (tmp_path / "README.md").write_text("<!-- s3-compat:start -->\n<!-- s3-compat:end -->\n")
    assert report.main(["--repo", str(tmp_path)]) == 2
    assert message in capsys.readouterr().err


def test_the_committed_page_matches_the_committed_results():
    assert report.main(["--check"]) == 0


def test_an_ingested_run_keeps_the_date_of_the_run_that_produced_it(tmp_path):
    """A stale artifact must not look newly executed: its date is its run's, however often it is ingested."""
    repo = tmp_path / "repo"
    (repo / "tests/s3-compat/servers").mkdir(parents=True)
    src = tmp_path / "dl"
    for sub, date in (("ci", "2026-11-14"), ("aws", "2026-11-02")):
        (src / sub / f"s3-compat-results-{sub}").mkdir(parents=True)
        (src / sub / "RUN_DATE").write_text(date + "\n")
        line = dict(case("a", ["put_get_head"], "pass"), server=sub)
        (src / sub / f"s3-compat-results-{sub}" / f"results-{sub}.jsonl").write_text(json.dumps(line) + "\n")
    report.ingest(str(src), str(repo))
    again = report.ingest(str(src), str(repo))
    assert sorted(again) == ["tests/s3-compat/results/aws.json", "tests/s3-compat/results/ci.json"]
    dates = {p.stem: json.loads(p.read_text())["run_date"] for p in (repo / "tests/s3-compat/results").glob("*.json")}
    assert dates == {"ci": "2026-11-14", "aws": "2026-11-02"}


def test_a_malformed_run_date_is_refused(tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    src = tmp_path / "dl"
    src.mkdir()
    (src / "RUN_DATE").write_text("last tuesday\n")
    (src / "results-x.jsonl").write_text(json.dumps(dict(case("a", ["put_get_head"], "pass"), server="x")) + "\n")
    with pytest.raises(report.Refused, match="not a YYYY-MM-DD date"):
        report.ingest(str(src), str(repo))


@pytest.mark.parametrize("server", ["../../.github/workflows/evil", "a/b", ".hidden", "", "MinIO", 7])
def test_an_ingested_server_that_is_not_a_plain_id_is_refused(tmp_path, server):
    """The lines come from a downloaded artifact, and the id names the file written under RESULTS."""
    repo = tmp_path / "repo"
    repo.mkdir()
    src = tmp_path / "dl"
    src.mkdir()
    (src / "results-x.jsonl").write_text(json.dumps(dict(case("a", ["put_get_head"], "pass"), server=server)) + "\n")
    with pytest.raises(report.Refused, match="is not a server id"):
        report.ingest(str(src), str(repo))
    assert not (tmp_path / ".github").exists() and not (repo / report.RESULTS).exists()
